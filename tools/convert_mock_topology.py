def endpoint_sets(data: Json) -> list[Json]:
    """NvcmServiceEndpointSet rows for the service keys present in a context."""
    rows = []
    for key, service in SERVICE_KEYS.items():
        block = data.get(key)
        if isinstance(block, dict) and (block.get("ipv4") or block.get("ipv6")):
            rows.append(
                clean({"service": service, "ipv4": block.get("ipv4"), "ipv6": block.get("ipv6")})
            )
    return rows


def dhcp_server_sets(data: Json) -> list[Json]:
    """NvcmDhcpServerSet rows for every provider block under ``dhcp`` except ``options``."""
    rows = []
    for name, block in (data.get("dhcp") or {}).items():
        if name == "options" or not isinstance(block, dict):
            continue
        rows.append(clean({"name": name, "ipv4": block.get("ipv4"), "ipv6": block.get("ipv6")}))
    return rows


def dhcp_option_sets(data: Json, gaps: Gaps) -> list[Json]:
    """NvcmDhcpOptionSet rows from ``dhcp.options.interface_roles`` and ``interface_names``."""
    rows = []
    options = (data.get("dhcp") or {}).get("options") or {}
    for source_key, match_kind in OPTION_SET_MATCH.items():
        for match_value, block in (options.get(source_key) or {}).items():
            rows.append(
                clean(
                    {
                        "name": f"{match_kind}:{match_value}",
                        "match_kind": match_kind,
                        "match_value": match_value,
                        "subnet_options": block.get("subnet_options"),
                        "reservation_options": block.get("reservation_options"),
                        "subnet_config": block.get("subnet_config"),
                        "client_id_template": block.get("client_id_template"),
                    }
                )
            )
    for key in set(options) - set(OPTION_SET_MATCH):
        gaps.note("dhcp.options key without home", key)
    return rows


def profile_object(name: str, data: Json, scope: Json, gaps: Gaps) -> Json | None:
    """NvcmServiceProfile row, or None when the context carries no service data."""
    endpoints = endpoint_sets(data)
    servers = dhcp_server_sets(data)
    option_rows = dhcp_option_sets(data, gaps)
    prefixes = data.get("management_prefixes") or {}
    if not (endpoints or servers or option_rows or prefixes):
        return None
    return clean(
        {
            "name": name,
            "description": scope.get("description"),
            "weight": scope.get("weight"),
            "is_active": scope.get("is_active"),
            "management_prefixes_ipv4": prefixes.get("ipv4"),
            "management_prefixes_ipv6": prefixes.get("ipv6"),
            "locations": scope.get("locations"),
            "device_roles": scope.get("roles"),
            "platforms": scope.get("platforms"),
            "devices": scope.get("devices"),
            "endpoint_sets": {"kind": "NvcmServiceEndpointSet", "data": endpoints}
            if endpoints
            else None,
            "dhcp_servers": {"kind": "NvcmDhcpServerSet", "data": servers} if servers else None,
            "dhcp_option_sets": {"kind": "NvcmDhcpOptionSet", "data": option_rows}
            if option_rows
            else None,
        }
    )


def local_context_groups(blueprint: Blueprint) -> dict[str, tuple[Json, list[str]]]:
    """Device-local service payloads grouped by content, name to (payload, devices)."""
    groups: dict[str, tuple[Json, list[str]]] = {}
    for device in blueprint.devices:
        context = device.get("config_context") or {}
        payload = {key: context[key] for key in sorted(context) if key in PROFILE_KEYS}
        if not payload:
            continue
        name = f"device-local-services-{stable_suffix(payload)}"
        groups.setdefault(name, (payload, []))[1].append(device["name"])
    return groups


def build_service_profiles(blueprint: Blueprint) -> list[Json]:
    """Profiles from location/role config contexts plus de-duplicated device-local ones."""
    rows = []
    for context in blueprint.config_contexts:
        data = context.get("data") or {}
        note_unhandled_context(data, blueprint.gaps)
        for key in ("tenants", "tags"):
            if context.get(key):
                blueprint.gaps.note(f"config context scope '{key}' without home", context["name"])
        profile = profile_object(context["name"], data, context, blueprint.gaps)
        if profile:
            rows.append(profile)
    for name, (payload, devices) in sorted(local_context_groups(blueprint).items()):
        scope = {
            "description": "Device local config context, merged by content",
            "weight": LOCAL_PROFILE_WEIGHT,
            "devices": sorted(devices),
        }
        profile = profile_object(name, payload, scope, blueprint.gaps)
        if profile:
            rows.append(profile)
    return [document("NvcmServiceProfile", rows)]


def build_credentials(blueprint: Blueprint) -> list[Json]:
    """NvcmCredentialMapping from ``password_mappings`` in device and location contexts."""
    mappings: dict[str, Json] = {}

    def add(scope_key: str, scope_value: str, username: str, entry: Json) -> None:
        slug = re.sub(r"[^a-z0-9]+", "-", scope_value.lower()).strip("-")
        name = f"{slug}-{username}"
        row = mappings.setdefault(
            name,
            {
                "name": name,
                "username": username,
                "secret_name": entry.get("password"),
                "rotation": entry.get("rotation"),
                "role": entry.get("role"),
            },
        )
        scoped = row.setdefault(scope_key, [])
        if scope_value not in scoped:
            scoped.append(scope_value)

    for device in blueprint.devices:
        platform = platform_name(device)
        for username, entry in (
            (device.get("config_context") or {}).get("password_mappings") or {}
        ).items():
            if platform:
                add("platforms", platform, username, entry)
            else:
                add("devices", device["name"], username, entry)
    for context in blueprint.config_contexts:
        for username, entry in ((context.get("data") or {}).get("password_mappings") or {}).items():
            for location in context.get("locations", []):
                add("locations", location, username, entry)
    return [document("NvcmCredentialMapping", [clean(mappings[name]) for name in sorted(mappings)])]


