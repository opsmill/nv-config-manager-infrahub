class NoAliasDumper(yaml.SafeDumper):
    """YAML dumper that never emits anchors, so repeated HFID lists stay readable."""

    def ignore_aliases(self, data: object) -> bool:  # noqa: ARG002
        """Disable anchor generation for every value."""
        return True


class Gaps:
    """Collects source values that have no home in the Infrahub schema."""

    def __init__(self) -> None:
        """Create an empty collector."""
        self._items: dict[str, set[str]] = defaultdict(set)

    def note(self, topic: str, value: object) -> None:
        """Record one unmapped value under a topic."""
        self._items[topic].add(str(value))

    def report(self) -> str:
        """Render the collected gaps as indented text."""
        lines = []
        for topic in sorted(self._items):
            values = ", ".join(sorted(self._items[topic]))
            lines.append(f"  - {topic}: {values}")
        return "\n".join(lines) if lines else "  (none)"


@dataclass
class Blueprint:
    """Everything the converter needs from one blueprint directory."""

    name: str
    deployment_name: str
    settings: Json
    devices: list[Json]
    vxlans: list[Json]
    overlay_assignments: list[tuple[str, str]]
    gaps: Gaps = field(default_factory=Gaps)

    @property
    def locations(self) -> list[Json]:
        """Location rows from locations.yaml with the deployment name rendered."""
        return [
            {**row, "name": self.render(row["name"]), "parent": self.render(row.get("parent"))}
            for row in self.settings.get("locations", [])
        ]

    @property
    def config_contexts(self) -> list[Json]:
        """Config context rows with the deployment name rendered in their scopes."""
        rendered = []
        for context in self.settings.get("config_contexts", []):
            row = dict(context)
            row["name"] = self.render(row.get("name", ""))
            for key in ("locations", "roles", "tenants", "tags"):
                row[key] = [self.render(value) for value in row.get(key, []) or []]
            rendered.append(row)
        return rendered

    @property
    def global_tenant(self) -> str | None:
        """Tenant applied to prefixes, VLANs and overlays by the design job."""
        return (self.settings.get("global_defaults") or {}).get("tenant")

    def render(self, value: str | None) -> str | None:
        """Replace the deployment-name placeholder used by the design job."""
        if value is None:
            return None
        for placeholder in DEPLOYMENT_PLACEHOLDERS:
            value = value.replace(placeholder, self.deployment_name)
        return value


@dataclass
class PrefixRecord:
    """A prefix the design job would have created, with its Nautobot decorations."""

    prefix: str
    nautobot_role: str | None
    tags: set[str]
    from_management: bool = False

    @property
    def network(self) -> IPNetwork:
        """The prefix as an ipaddress network."""
        return ipaddress.ip_network(self.prefix, strict=False)


@dataclass
class IpRecord:
    """An IP address owned by a loaded interface, or seen as a BGP peer address."""

    address: str
    device: str | None = None
    interface: str | None = None
    vrf: str | None = None
    role: str | None = None
    dhcp_reservation: bool = False
    dhcp_pool: bool = False
    description: str | None = None

    @property
    def host(self) -> str:
        """Host part of the address."""
        return str(ipaddress.ip_interface(self.address).ip)


@dataclass
class BgpSession:
    """One directed BGP session as the schema-library routing_bgp extension models it."""

    device: str
    vrf: str | None
    local_asn: int
    remote_asn: int
    remote_device: str
    remote_interface: str | None
    remote_ip: str | None
    local_ip: str | None
    peer_group: str | None

    @property
    def description(self) -> str:
        """Unique description, required by RoutingProtocol."""
        group = self.peer_group or "eBGP"
        target = ipaddress.ip_interface(self.remote_ip).ip if self.remote_ip else "unknown"
        return f"{self.device} {group} to {self.remote_device} {target}"


# --------------------------------------------------------------------------- loading


def load_yaml(path: Path) -> Json:
    """Read a YAML mapping, returning an empty mapping for missing or scalar files."""
    if not path.is_file():
        return {}
    with path.open(encoding="utf-8") as handle:
        data = yaml.safe_load(handle)
    return data if isinstance(data, dict) else {}


def load_context_yaml(directory: Path) -> Json:
    """Merge every top-level YAML mapping in a context directory."""
    merged: Json = {}
    for path in sorted(directory.glob("*.yaml")) + sorted(directory.glob("*.yml")):
        merged.update(load_yaml(path))
    return merged


def mock_serial(device_name: str) -> str:
    """Stable serial for non-Cumulus mock devices, as the design job assigns it."""
    slug = re.sub(r"[^a-z0-9]+", "", device_name.lower())
    return f"MOCK-{slug.upper()}"


def load_devices(
    devices_dir: Path, pattern: str
) -> tuple[list[Json], list[Json], list[tuple[str, str]]]:
    """Load device payloads, their VXLANs and device-scoped overlay assignments."""
    devices: list[Json] = []
    vxlans: dict[int, Json] = {}
    raw_assignments: list[tuple[str, str]] = []
    for path in sorted(devices_dir.glob(pattern)):
        payload = json.loads(path.read_text(encoding="utf-8")).get("data", {})
        device = payload.get("device")
        if not device:
            continue
        if not device.get("serial"):
            device["serial"] = mock_serial(device["name"])
        devices.append(device)
        for vxlan in payload.get("vxlans", []):
            if vxlan.get("vnid") is not None:
                vxlans.setdefault(int(vxlan["vnid"]), vxlan)
        for assignment in payload.get("overlay_assignments", []):
            object_type = assignment.get("assigned_object_type") or {}
            if (object_type.get("app_label"), object_type.get("model")) != ("dcim", "device"):
                continue
            raw_assignments.append(
                (assignment["overlay"]["name"], assignment["assigned_object_id"])
            )
    names_by_id = {device.get("id"): device["name"] for device in devices}
    assignments = sorted(
        {(overlay, names_by_id[obj]) for overlay, obj in raw_assignments if obj in names_by_id}
    )
    return devices, [vxlans[vnid] for vnid in sorted(vxlans)], assignments


def load_blueprint(
    blueprint_dir: Path, common_dir: Path, deployment: str, pattern: str
) -> Blueprint:
    """Assemble a Blueprint from the context directories."""
    settings = {**load_context_yaml(common_dir), **load_context_yaml(blueprint_dir)}
    devices, vxlans, assignments = load_devices(blueprint_dir / "devices", pattern)
    blueprint = Blueprint(
        name=blueprint_dir.name,
        deployment_name=deployment,
        settings=settings,
        devices=devices,
        vxlans=vxlans,
        overlay_assignments=assignments,
    )
    for device in devices:
        location = device.get("location") or {}
        if location.get("name"):
            location["name"] = blueprint.render(location["name"])
    return blueprint


# --------------------------------------------------------------------------- helpers


def document(kind: str, data: list[Json]) -> Json:
    """Wrap object rows in the infrahub.app/v1 Object envelope."""
    return {"apiVersion": API_VERSION, "kind": "Object", "spec": {"kind": kind, "data": data}}


def clean(mapping: Json) -> Json:
    """Drop keys whose value is unset so the attribute stays unset in Infrahub."""
    return {key: value for key, value in mapping.items() if value not in (None, [], {}, "")}


def named(value: object) -> str | None:
    """Return the ``name`` of a Nautobot reference mapping, or None."""
    if isinstance(value, dict):
        return value.get("name")
    return value if isinstance(value, str) else None


def ip_ref(address: str) -> list[str]:
    """HFID reference for an IpamIPAddress in the default namespace."""
    return [IP_NAMESPACE, address]


def as_ref(asn: int) -> list[str]:
    """HFID reference for a RoutingAutonomousSystem (GraphQL HFID components are strings)."""
    return [str(asn), as_name(asn)]


def as_name(asn: int) -> str:
    """Name given to an autonomous system object."""
    return f"AS{asn}"


def role_name(entity: Json) -> str:
    """Role name of a device or interface payload, empty when unset."""
    return named(entity.get("role")) or ""


def platform_name(device: Json) -> str | None:
    """Platform name of a device payload."""
    return named(device.get("platform"))


def is_cumulus(device: Json) -> bool:
    """Whether the device runs Cumulus Linux and is therefore NVCM managed."""
    return CUMULUS_PLATFORM in (platform_name(device) or "")


def is_management_interface(interface: Json) -> bool:
    """Apply the design job's definition of a management interface."""
    name = interface.get("name", "")
    return name == "eth0" or name.startswith("Management") or bool(interface.get("mgmt_only"))


def dhcp_flags(interface: Json, smn_device: bool) -> tuple[bool, bool]:
    """Return (pool, reservation) as the design job's ip_addresses template decides them."""
    explicit_pool = bool(interface.get("dhcp_pool"))
    reserve = bool(interface.get("dhcp_reserve")) or is_management_interface(interface)
    smn_uplink = smn_device and role_name(interface) == "Uplink"
    if explicit_pool:
        return True, False
    if reserve:
        return False, True
    return smn_uplink, False


def interface_type_label(interface: Json) -> str | None:
    """Nautobot interface type as the design template renders it, e.g. 400gbase-x-osfp."""
    itype = (interface.get("type") or "").lower()
    if not itype:
        return None
    return itype.removeprefix("a_").replace("_", "-")


def interface_kind(interface: Json) -> str:
    """Infrahub interface kind for a Nautobot interface type."""
    itype = (interface.get("type") or "").upper()
    if itype == "LAG":
        return LAG_KIND
    if itype in {"VIRTUAL", "BRIDGE"}:
        return VIRTUAL_KIND
    return PHYSICAL_KIND


def map_interface_role(interface: Json) -> str | None:
    """Return the Nautobot interface role verbatim; DcimInterface.role is free text."""
    return role_name(interface) or None


def map_device_status(status: object) -> str:
    """Map a Nautobot status name onto the adapted DcimDevice status dropdown."""
    name = (named(status) or "active").lower()
    return DEVICE_STATUS.get(name, "unknown")


def role_category(name: str) -> str:
    """Coarse NvcmDeviceRole category derived from the role name."""
    upper = name.upper()
    if name in WAN_ROLES:
        return "wan_router"
    if any(hint in upper for hint in COMPUTE_HINTS):
        return "compute"
    if any(hint in upper for hint in MANAGEMENT_HINTS):
        return "management"
    if "STORAGE" in upper and not any(part in upper for part in ("LEAF", "SPINE", "SWITCH")):
        return "storage"
    return "network"


def containing_prefix(
    network: IPNetwork, candidates: Iterable[PrefixRecord]
) -> PrefixRecord | None:
    """Smallest candidate prefix that strictly contains ``network``."""
    best: PrefixRecord | None = None
    for record in candidates:
        parent = record.network
        if network.version != parent.version or network == parent or not network.subnet_of(parent):
            continue
        if best is None or parent.prefixlen > best.network.prefixlen:
            best = record
    return best


def stable_suffix(payload: object) -> str:
    """Short deterministic hash used to name de-duplicated device-local profiles."""
    digest = hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()
    return digest[:8]


