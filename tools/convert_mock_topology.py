r"""Convert an NVCM mock-topology blueprint into Infrahub object files.

The NVCM repository ships mock topologies under
``development/mock_topology/context/<blueprint>/`` as Nautobot-shaped YAML and
JSON (one JSON file per device, plus locations, aggregate prefixes, BGP seeds
and InfiniBand PKeys), with shared lookup tables in ``context/common/``. This
tool maps that data onto the Infrahub schema in ``schemas/`` and writes
``infrahubctl object load`` files under ``objects/<blueprint>/`` with numbered
load-order prefixes.

Nothing is invented: every attribute comes from a source field and attributes
whose source is absent are left unset. Source fields that have no home in the
schema are collected and printed at the end of a run so they can be reported.

Example:
    uv run tools/convert_mock_topology.py \
        /path/to/nv-config-manager/development/mock_topology/context/superpod

"""

