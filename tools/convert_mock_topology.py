def collect_prefixes(blueprint: Blueprint) -> list[PrefixRecord]:
    """Prefixes the design job creates: aggregates, /31 links and DHCP subnets."""
    records: dict[str, PrefixRecord] = {}
    for aggregate in blueprint.settings.get("aggregate_prefixes") or []:
        records[aggregate["prefix"]] = PrefixRecord(
            aggregate["prefix"], aggregate.get("role"), set(aggregate.get("tags") or [])
        )
    aggregates = list(records.values())
    dhcp_subnets: dict[str, bool] = {}
    for device in blueprint.devices:
        smn = role_name(device).startswith("SMN")
        for interface in device.get("interfaces", []):
            pool, reservation = dhcp_flags(interface, smn)
            for address in interface.get("ip_addresses", []):
                if not address.get("address"):
                    continue
                network = ipaddress.ip_network(address["address"], strict=False)
                if pool or reservation:
                    from_mgmt = is_management_interface(interface) and not pool
                    dhcp_subnets[str(network)] = dhcp_subnets.get(str(network), False) or from_mgmt
                if network.prefixlen in (31, 127) and str(network) not in records:
                    parent = containing_prefix(network, aggregates)
                    records[str(network)] = PrefixRecord(
                        str(network), parent.nautobot_role if parent else None, set()
                    )
    for prefix, from_mgmt in dhcp_subnets.items():
        if prefix not in records:
            parent = containing_prefix(ipaddress.ip_network(prefix), aggregates)
            records[prefix] = PrefixRecord(prefix, parent.nautobot_role if parent else None, set())
        records[prefix].tags.add("dhcp-subnet")
        records[prefix].from_management = from_mgmt
    return sorted(records.values(), key=lambda record: (record.network.prefixlen, record.network))


def prefix_flags(record: PrefixRecord, gaps: Gaps) -> Json:
    """Booleans replacing the role-aggregate and uc-jumphost tags; other tags are gaps."""
    for tag in record.tags - {"role-aggregate", "uc-jumphost", "dhcp-subnet"}:
        gaps.note("prefix tag without home", tag)
    return {
        "site_aggregate": True if "role-aggregate" in record.tags else None,
        "uc_jumphost": True if "uc-jumphost" in record.tags else None,
    }


def build_prefixes(
    blueprint: Blueprint, index: LocationIndex, records: list[PrefixRecord]
) -> list[Json]:
    """IpamPrefix objects scoped to the site, Nautobot role name kept verbatim."""
    site = index.default_site()
    scope = index.reference(site) if site else None
    data = []
    for record in records:
        has_children = any(
            other.network != record.network and other.network.subnet_of(record.network)
            for other in records
            if other.network.version == record.network.version
        )
        data.append(
            clean(
                {
                    "prefix": record.prefix,
                    "ip_namespace": IP_NAMESPACE,
                    "status": "active",
                    "role": record.nautobot_role,
                    **prefix_flags(record, blueprint.gaps),
                    "member_type": "prefix" if has_children else "address",
                    "tenant": blueprint.global_tenant,
                    "scope": scope,
                }
            )
        )
    return [document("IpamPrefix", data)]


def collect_ip_records(blueprint: Blueprint) -> dict[str, IpRecord]:
    """Interface addresses keyed by address, first owner wins on duplicates."""
    records: dict[str, IpRecord] = {}
    for device in blueprint.devices:
        smn = role_name(device).startswith("SMN")
        for interface in device.get("interfaces", []):
            pool, reservation = dhcp_flags(interface, smn)
            management = is_management_interface(interface)
            for address in interface.get("ip_addresses", []):
                value = address.get("address")
                if not value:
                    continue
                if value in records:
                    blueprint.gaps.note("duplicate address across interfaces", value)
                    continue
                records[value] = IpRecord(
                    address=value,
                    device=device["name"],
                    interface=interface["name"],
                    vrf=named(interface.get("vrf")),
                    role="management" if management else None,
                    dhcp_reservation=reservation,
                    dhcp_pool=pool,
                )
    return records


def build_ip_addresses(records: dict[str, IpRecord]) -> list[Json]:
    """IpamIPAddress objects; the interface link is set from the interface side."""
    data = []
    for address in sorted(records, key=lambda value: ipaddress.ip_interface(value)):
        record = records[address]
        data.append(
            clean(
                {
                    "address": record.address,
                    "ip_namespace": IP_NAMESPACE,
                    "status": "active",
                    "role": record.role,
                    "description": record.description,
                    "vrf": record.vrf,
                    "dhcp_reservation": True if record.dhcp_reservation else None,
                }
            )
        )
    return [document("IpamIPAddress", data)]


