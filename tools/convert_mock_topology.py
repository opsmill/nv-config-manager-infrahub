def vxlan_row(vxlan: Json) -> Json:
    """NvcmVxlan component row."""
    return clean(
        {
            "vni": int(vxlan["vnid"]),
            "vni_type": vxlan.get("vni_type"),
            "l3_vlan_id": vxlan.get("l3_vlan_id"),
            "vlan": vlan_label(vxlan["vlan"]) if vxlan.get("vlan") else None,
            "vrf": named(vxlan.get("vrf")),
        }
    )


def build_overlays(blueprint: Blueprint, index: LocationIndex) -> list[Json]:
    """VXLAN EVPN overlays from device payloads and IB PKey overlays from ib_pkeys.yaml."""
    location = index.reference(index.default_location)
    by_overlay: dict[str, list[Json]] = defaultdict(list)
    for vxlan in blueprint.vxlans:
        by_overlay[named(vxlan.get("overlay")) or vxlan["name"]].append(vxlan_row(vxlan))
    assignments: dict[str, list[str]] = defaultdict(list)
    for overlay, device in blueprint.overlay_assignments:
        assignments[overlay].append(device)
    rows = []
    for name in sorted(set(by_overlay) | set(assignments)):
        assigned = [{"name": device, "device": device} for device in sorted(set(assignments[name]))]
        rows.append(
            clean(
                {
                    "name": name,
                    "isolation_type": "vxlan_evpn",
                    "status": "active",
                    "location": location,
                    "tenant": blueprint.global_tenant,
                    "vxlans": {"kind": "NvcmVxlan", "data": by_overlay[name]}
                    if by_overlay[name]
                    else None,
                    "assignments": {"kind": "NvcmOverlayAssignment", "data": assigned}
                    if assigned
                    else None,
                }
            )
        )
    for overlay in blueprint.settings.get("ib_pkey_overlays") or []:
        pkeys = [
            clean(
                {
                    "pkey": pkey["pkey"],
                    "partition_name": pkey.get("name"),
                    "default_membership": pkey.get("membership_type"),
                }
            )
            for pkey in overlay.get("pkeys") or []
        ]
        rows.append(
            clean(
                {
                    "name": overlay["name"],
                    "description": overlay.get("description"),
                    "isolation_type": "ib_pkey",
                    "status": "active",
                    "location": location,
                    "tenant": blueprint.global_tenant,
                    "pkeys": {"kind": "NvcmInfinibandPkey", "data": pkeys} if pkeys else None,
                }
            )
        )
    return [document("NvcmOverlay", rows)]


