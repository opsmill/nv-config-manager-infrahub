def device_asns(blueprint: Blueprint) -> dict[str, int]:
    """Device name to ASN from the YAML seed and the JSON routing instances."""
    asns: dict[str, int] = {}
    for row in blueprint.settings.get("bgp_routing_instances") or []:
        if row.get("device") and row.get("asn") is not None:
            asns[row["device"]] = int(row["asn"])
    for device in blueprint.devices:
        for instance in device.get("bgp_routing_instances") or []:
            asn = (instance.get("autonomous_system") or {}).get("asn")
            if asn is not None:
                asns[device["name"]] = int(asn)
    return asns


def interface_ipv4(device: Json, name: str | None) -> str | None:
    """First IPv4 address on a named interface of a device payload."""
    for interface in device.get("interfaces", []):
        if interface["name"] == name:
            for address in interface.get("ip_addresses", []):
                if address.get("ip_version") == 4 and address.get("address"):
                    return address["address"]
    return None


def local_address_for(
    device: Json, remote: str | None, router_id_interface: str | None
) -> str | None:
    """Local session address: the on-link address for a p2p peer, else the router-id."""
    if remote is None:
        return None
    remote_interface = ipaddress.ip_interface(remote)
    if remote_interface.network.prefixlen < remote_interface.max_prefixlen:
        for interface in device.get("interfaces", []):
            for address in interface.get("ip_addresses", []):
                if not address.get("address"):
                    continue
                local = ipaddress.ip_interface(address["address"])
                if local.network == remote_interface.network and local.ip != remote_interface.ip:
                    return address["address"]
    return interface_ipv4(device, router_id_interface)


def sessions_from_instances(device: Json) -> list[BgpSession]:
    """Sessions from the ``bgp_routing_instances[].endpoints`` block of a device payload."""
    sessions: list[BgpSession] = []
    router_id = router_id_interface(device)
    for instance in device.get("bgp_routing_instances") or []:
        local_asn = int(instance["autonomous_system"]["asn"])
        for endpoint in instance.get("endpoints") or []:
            peer = endpoint.get("peer") or {}
            peer_instance = peer.get("routing_instance") or {}
            remote_device = named(peer_instance.get("device"))
            remote_asn = (peer_instance.get("autonomous_system") or {}).get("asn")
            if not remote_device or remote_asn is None:
                continue
            source = peer.get("source_interface") or {}
            remote_ip = next(
                (
                    ip["address"]
                    for ip in source.get("ip_addresses", [])
                    if ip.get("ip_version") == 4
                ),
                peer.get("source_ip"),
            )
            sessions.append(
                BgpSession(
                    device=device["name"],
                    vrf=named((endpoint.get("source_interface") or {}).get("vrf")),
                    local_asn=local_asn,
                    remote_asn=int(remote_asn),
                    remote_device=remote_device,
                    remote_interface=source.get("name"),
                    remote_ip=remote_ip,
                    local_ip=local_address_for(device, remote_ip, router_id),
                    peer_group=named(endpoint.get("peer_group")),
                )
            )
    return sessions


def sessions_from_seed(blueprint: Blueprint, asns: dict[str, int]) -> list[BgpSession]:
    """Both directions of each ``bgp_peerings`` seed row whose devices are loaded."""
    devices = {device["name"]: device for device in blueprint.devices}
    sessions: list[BgpSession] = []
    for row in blueprint.settings.get("bgp_peerings") or []:
        ends = (
            (row.get("device"), row.get("source_interface")),
            (row.get("peer_device"), row.get("peer_source_interface")),
        )
        for (local, local_intf), (remote, remote_intf) in (ends, ends[::-1]):
            if (
                local not in devices
                or remote not in devices
                or local not in asns
                or remote not in asns
            ):
                blueprint.gaps.note(
                    "bgp_peerings row with unknown device or ASN", f"{local} <-> {remote}"
                )
                continue
            local_vrf = next(
                (
                    named(i.get("vrf"))
                    for i in devices[local]["interfaces"]
                    if i["name"] == local_intf
                ),
                None,
            )
            sessions.append(
                BgpSession(
                    device=local,
                    vrf=local_vrf,
                    local_asn=asns[local],
                    remote_asn=asns[remote],
                    remote_device=remote,
                    remote_interface=remote_intf,
                    remote_ip=interface_ipv4(devices[remote], remote_intf),
                    local_ip=interface_ipv4(devices[local], local_intf),
                    peer_group=None,
                )
            )
    return sessions


def collect_sessions(blueprint: Blueprint, asns: dict[str, int]) -> list[BgpSession]:
    """All sessions, de-duplicated on (device, remote address, peer group)."""
    unique: dict[tuple[str, str | None, str | None], BgpSession] = {}
    for device in blueprint.devices:
        for session in sessions_from_instances(device):
            unique.setdefault((session.device, session.remote_ip, session.peer_group), session)
    for session in sessions_from_seed(blueprint, asns):
        unique.setdefault((session.device, session.remote_ip, session.peer_group), session)
    return sorted(unique.values(), key=lambda session: (session.device, session.description))


