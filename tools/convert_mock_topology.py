def option_definitions(blueprint: Blueprint) -> list[Json]:
    """NvcmDhcpOptionDefinition rows from every ``Dhcp4.option-def`` block."""
    definitions: dict[tuple[str, str], Json] = {}
    sources = [
        (context.get("data") or {}, context.get("locations", []))
        for context in blueprint.config_contexts
    ]
    sources += [(device.get("config_context") or {}, []) for device in blueprint.devices]
    for data, locations in sources:
        for entry in (data.get("Dhcp4") or {}).get("option-def") or []:
            key = (entry.get("space") or "dhcp4", entry["name"])
            row = definitions.setdefault(
                key,
                {
                    "name": entry["name"],
                    "code": entry["code"],
                    "space": key[0],
                    "option_type": entry.get("type"),
                    "array": entry.get("array"),
                    "record_types": entry.get("record-types"),
                    "encapsulate": entry.get("encapsulate"),
                    "locations": [],
                },
            )
            row["locations"] = sorted(set(row["locations"]) | set(locations))
    return [clean(row) for _, row in sorted(definitions.items())]


def pool_ranges(hosts: Iterable[str]) -> list[tuple[str, str]]:
    """Merge hosts into contiguous (start, end) ranges."""
    ordered = sorted({ipaddress.ip_address(host) for host in hosts})
    ranges: list[tuple[str, str]] = []
    start = previous = None
    for host in ordered:
        if previous is not None and int(host) == int(previous) + 1:
            previous = host
            continue
        if start is not None and previous is not None:
            ranges.append((str(start), str(previous)))
        start = previous = host
    if start is not None and previous is not None:
        ranges.append((str(start), str(previous)))
    return ranges


def pool_gateways(blueprint: Blueprint, ip_records: dict[str, IpRecord]) -> dict[str, str]:
    """Prefix to gateway address as ``_load_prefix_gateway_relationships`` derives it."""
    gateways: dict[str, str] = {}
    by_host = {record.host: record.address for record in ip_records.values()}
    for device in blueprint.devices:
        for interface in device.get("interfaces", []):
            if not interface.get("dhcp_pool"):
                continue
            for address in interface.get("ip_addresses", []):
                if not address.get("address"):
                    continue
                local = ipaddress.ip_interface(address["address"])
                if local.network.prefixlen not in (31, 127):
                    continue
                gateway = next(str(host) for host in local.network if host != local.ip)
                if gateway in by_host:
                    gateways.setdefault(str(local.network), by_host[gateway])
                else:
                    blueprint.gaps.note("DHCP gateway address not loaded", gateway)
    return gateways


def build_dhcp(
    blueprint: Blueprint, records: list[PrefixRecord], ip_records: dict[str, IpRecord]
) -> list[Json]:
    """Option definitions plus one NvcmDhcpScope per prefix the design tagged dhcp-subnet."""
    dhcp_records = [record for record in records if "dhcp-subnet" in record.tags]
    pools_by_prefix: dict[str, list[str]] = defaultdict(list)
    for record in ip_records.values():
        if not record.dhcp_pool:
            continue
        owner = containing_prefix(ipaddress.ip_network(record.address, strict=False), dhcp_records)
        exact = next(
            (
                r
                for r in dhcp_records
                if r.network == ipaddress.ip_network(record.address, strict=False)
            ),
            None,
        )
        target = exact or owner
        if target:
            pools_by_prefix[target.prefix].append(record.host)
    gateways = pool_gateways(blueprint, ip_records)
    scopes = []
    for record in dhcp_records:
        pools = [
            {"name": f"{record.prefix} {start}-{end}", "start": start, "end": end}
            for start, end in pool_ranges(pools_by_prefix.get(record.prefix, []))
        ]
        scopes.append(
            clean(
                {
                    "name": record.prefix,
                    "prefix": [IP_NAMESPACE, record.prefix],
                    "enabled": True,
                    "gateway": ip_ref(gateways[record.prefix])
                    if record.prefix in gateways
                    else None,
                    "pools": {"kind": "NvcmDhcpPool", "data": pools} if pools else None,
                }
            )
        )
    return [
        document("NvcmDhcpOptionDefinition", option_definitions(blueprint)),
        document("NvcmDhcpScope", scopes),
    ]


def build_firmware_targets(
    blueprint: Blueprint, roles: set[str], platforms: set[str]
) -> list[Json]:
    """NvcmFirmwareTarget rows from location-firmware-targets shaped config contexts."""
    by_upper = {role.upper(): role for role in roles}
    rows = []
    for context in blueprint.config_contexts:
        data = context.get("data") or {}
        for key, block in data.items():
            if key in HANDLED_CONTEXT_KEYS or not isinstance(block, dict):
                continue
            role = by_upper.get(key.upper().replace("_", "-"))
            targets = {p: v for p, v in block.items() if p in platforms and isinstance(v, str)}
            if role is None or not targets:
                continue
            for location in context.get("locations", []):
                for platform, version in targets.items():
                    rows.append(
                        {
                            "location": location,
                            "device_role": role,
                            "platform": platform,
                            "desired_version": version,
                        }
                    )
    return [document("NvcmFirmwareTarget", rows)] if rows else []


