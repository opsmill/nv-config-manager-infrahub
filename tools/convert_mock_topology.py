def build_cables(blueprint: Blueprint) -> list[Json]:
    """One DcimCable per physical link whose both ends are loaded devices."""
    kinds = {
        device["name"]: {
            intf["name"]: interface_kind(intf) for intf in device.get("interfaces", [])
        }
        for device in blueprint.devices
    }
    seen: set[tuple[tuple[str, str], tuple[str, str]]] = set()
    for device in blueprint.devices:
        for interface in device.get("interfaces", []):
            remote = interface.get("connected_interface") or {}
            remote_device, remote_name = named(remote.get("device")), remote.get("name")
            if not remote_device or not remote_name or remote_device not in kinds:
                continue
            if remote_name not in kinds[remote_device]:
                blueprint.gaps.note(
                    "cable to an interface missing on the remote device",
                    f"{remote_device} {remote_name}",
                )
                continue
            local = (device["name"], interface["name"])
            far = (remote_device, remote_name)
            if kinds[local[0]][local[1]] != PHYSICAL_KIND or kinds[far[0]][far[1]] != PHYSICAL_KIND:
                blueprint.gaps.note("cable on a non-physical interface", f"{local} -> {far}")
                continue
            seen.add(tuple(sorted((local, far))))  # type: ignore[arg-type]
    data = []
    for end_a, end_b in sorted(seen):
        data.append(
            {
                "label": f"{end_a[0]}:{end_a[1]}--{end_b[0]}:{end_b[1]}",
                "status": "connected",
                "connected_endpoints": [
                    {"kind": PHYSICAL_KIND, "data": {"device": end_a[0], "name": end_a[1]}},
                    {"kind": PHYSICAL_KIND, "data": {"device": end_b[0], "name": end_b[1]}},
                ],
            }
        )
    return [document("DcimCable", data)]


