def write_documents(path: Path, documents: list[Json], blueprint_name: str) -> int:
    """Write non-empty documents to one file; return the number of top-level objects."""
    populated = [doc for doc in documents if doc["spec"]["data"]]
    if not populated:
        LOGGER.info("skipping %s, nothing to write", path.name)
        return 0
    chunks = [GENERATED_HEADER.format(name=blueprint_name)]
    for doc in populated:
        chunks.append(
            "---\n"
            + yaml.dump(doc, Dumper=NoAliasDumper, sort_keys=False, width=1000, allow_unicode=True)
        )
    path.write_text("".join(chunks), encoding="utf-8")
    count = sum(len(doc["spec"]["data"]) for doc in populated)
    LOGGER.info("wrote %s (%d objects)", path.name, count)
    return count


def convert(blueprint: Blueprint, output_dir: Path) -> dict[str, int]:
    """Run every builder in load order and write the object files."""
    index = LocationIndex(blueprint)
    prefix_records = collect_prefixes(blueprint)
    ip_records = collect_ip_records(blueprint)
    bgp_documents = build_bgp(blueprint, ip_records)  # adds BGP peer addresses to ip_records
    roles = {row["name"] for row in build_roles(blueprint)[0]["spec"]["data"]}
    platforms = {row["name"] for row in build_platforms_and_types(blueprint)[0]["spec"]["data"]}
    files: list[tuple[str, list[Json]]] = [
        ("00-organizations.yml", build_organizations(blueprint)),
        ("10-locations.yml", build_locations(blueprint, index)),
        ("20-roles.yml", build_roles(blueprint) + build_tags(blueprint)),
        ("30-platforms-device-types.yml", build_platforms_and_types(blueprint)),
        (
            "40-namespaces-vrfs-vlans.yml",
            build_vrfs(blueprint) + build_vlan_groups(blueprint, index),
        ),
        ("50-prefixes.yml", build_prefixes(blueprint, index, prefix_records)),
        ("55-ip-addresses.yml", build_ip_addresses(ip_records)),
        ("60-devices.yml", build_devices(blueprint, index)),
        ("80-cables.yml", build_cables(blueprint)),
        ("85-bgp.yml", bgp_documents),
        ("90-nvcm-state.yml", build_device_status(blueprint)),
        ("91-service-profiles.yml", build_service_profiles(blueprint)),
        ("92-dhcp.yml", build_dhcp(blueprint, prefix_records, ip_records)),
        ("93-firmware.yml", build_firmware_targets(blueprint, roles, platforms)),
        ("94-credentials.yml", build_credentials(blueprint)),
        ("95-overlays.yml", build_overlays(blueprint, index)),
    ]
    output_dir.mkdir(parents=True, exist_ok=True)
    for stale in output_dir.glob("*.yml"):
        stale.unlink()
    return {
        name: write_documents(output_dir / name, documents, blueprint.name)
        for name, documents in files
    }


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    """Command line arguments."""
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "blueprint_dir", type=Path, help="mock_topology/context/<blueprint> directory"
    )
    parser.add_argument(
        "--common-dir", type=Path, help="context/common directory (default: sibling of blueprint)"
    )
    parser.add_argument(
        "--output-dir", type=Path, help="destination (default: objects/<blueprint> in the repo)"
    )
    parser.add_argument(
        "--deployment-name", default="test", help="value for {{ deployment_name }} (default: test)"
    )
    parser.add_argument(
        "--device-glob", default="*.json", help="glob for devices/*.json (default: *.json)"
    )
    parser.add_argument("-v", "--verbose", action="store_true", help="debug logging")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    """Entry point."""
    args = parse_args(argv)
    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO, format="%(levelname)s %(message)s"
    )
    blueprint_dir = args.blueprint_dir.resolve()
    common_dir = (args.common_dir or blueprint_dir.parent / "common").resolve()
    output_dir = (
        args.output_dir or Path(__file__).resolve().parent.parent / "objects" / blueprint_dir.name
    )
    blueprint = load_blueprint(blueprint_dir, common_dir, args.deployment_name, args.device_glob)
    LOGGER.info("loaded %d devices from %s", len(blueprint.devices), blueprint_dir)
    counts = convert(blueprint, output_dir)
    print(f"\nWrote {sum(counts.values())} top-level objects to {output_dir}")
    print("Source data without a home in the schema:")
    print(blueprint.gaps.report())
    return 0


if __name__ == "__main__":
    sys.exit(main())
